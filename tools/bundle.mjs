#!/usr/bin/env node
/**
 * Bundles the Luau source tree into one executor-friendly chunk.
 *
 * Usage:
 *   node tools/bundle.mjs --out build/kaizax.luau
 *   node tools/bundle.mjs --out build/kaizax-demo.luau --demo examples/Demo.luau
 *   node tools/bundle.mjs --out build/kaizax-test.luau --demo examples/Demo.luau --harness test/harness.luau
 *
 * Requires inside src are rewritten from `require(script.Parent.X)` form into
 * `__require("id")` calls against an in-memory module table. No Roblox
 * instances are created for the library itself.
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const ROOT = path.resolve(process.cwd());
const SRC = path.join(ROOT, "src");

function walk(directory, files = []) {
	for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
		const full = path.join(directory, entry.name);
		if (entry.isDirectory()) {
			walk(full, files);
		} else if (entry.isFile() && entry.name.endsWith(".luau")) {
			files.push(full);
		}
	}
	return files;
}

function moduleId(file) {
	return path.relative(SRC, file).replace(/\\/g, "/").replace(/\.luau$/, "");
}

function rewriteRequires(source, id) {
	const parts = id === "init" ? [] : id.split("/");

	return source.replace(/require\(script((?:\.[A-Za-z_][A-Za-z0-9_]*)+)\)/g, (_, chain) => {
		const tokens = chain.slice(1).split(".");
		const resolved = [...parts];

		for (const token of tokens) {
			if (token === "Parent") resolved.pop();
			else resolved.push(token);
		}

		return `__require(${JSON.stringify(resolved.join("/"))})`;
	});
}

function requiredModules(source) {
	const found = new Set();
	for (const match of source.matchAll(/__require\("([^"]+)"\)/g)) {
		found.add(match[1]);
	}
	return found;
}

function parseArgs(argv) {
	const args = { out: null, demo: null, harness: null };
	for (let index = 2; index < argv.length; index += 1) {
		const arg = argv[index];
		if (arg === "--out") args.out = argv[++index];
		else if (arg === "--demo") args.demo = argv[++index];
		else if (arg === "--harness") args.harness = argv[++index];
		else throw new Error(`Unknown argument: ${arg}`);
	}
	if (!args.out) throw new Error("Missing --out path");
	return args;
}

const args = parseArgs(process.argv);
const files = walk(SRC).sort();
const factories = files.map((file) => {
	const id = moduleId(file);
	const source = rewriteRequires(fs.readFileSync(file, "utf8"), id);
	return { id, source };
});

const ids = new Set(factories.map((entry) => entry.id));
for (const { id, source } of factories) {
	for (const target of requiredModules(source)) {
		if (!ids.has(target)) {
			throw new Error(`Module ${id} requires missing module ${target}`);
		}
	}
}

const chunks = [];
chunks.push("-- Kaizax UI Library bundle. Generated by tools/bundle.mjs. Do not edit by hand.");
chunks.push("--!nonstrict");
chunks.push("");
chunks.push("local Kaizax = (function()");
chunks.push("\tlocal __modules = {}");
chunks.push("\tlocal __cache = {}");
chunks.push("");
chunks.push("\tlocal function __require(id)");
chunks.push("\t\tlocal cached = __cache[id]");
chunks.push("\t\tif cached ~= nil then");
chunks.push("\t\t\treturn cached");
chunks.push("\t\tend");
chunks.push("");
chunks.push("\t\tlocal factory = __modules[id]");
chunks.push("\t\tif not factory then");
chunks.push(`\t\t\terror(\`Kaizax bundle: unknown module '{id}'\`)`);
chunks.push("\t\tend");
chunks.push("");
chunks.push("\t\tlocal result = factory()");
chunks.push("\t\tif result == nil then");
chunks.push("\t\t\tresult = true");
chunks.push("\t\tend");
chunks.push("\t\t__cache[id] = result");
chunks.push("\t\treturn result");
chunks.push("\tend");
chunks.push("");

for (const { id, source } of factories) {
	chunks.push(`\t__modules[${JSON.stringify(id)}] = function()`);
	chunks.push(source.trimEnd());
	chunks.push("\tend");
	chunks.push("");
}

chunks.push(`\treturn __require("init")`);
chunks.push("end)()");
chunks.push("");

if (args.demo) {
	const demoSource = fs.readFileSync(path.resolve(ROOT, args.demo), "utf8");
	chunks.push("local Demo = (function()");
	chunks.push(demoSource.trimEnd());
	chunks.push("end)()");
	chunks.push("");
}

if (args.harness) {
	const harness = fs.readFileSync(path.resolve(ROOT, args.harness), "utf8");
	chunks.push(harness.trimEnd());
	chunks.push("");
} else {
	chunks.push("return Kaizax");
	chunks.push("");
}

const outPath = path.resolve(ROOT, args.out);
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, chunks.join("\n"), "utf8");
console.log(`Wrote ${outPath} (${chunks.join("\n").length} bytes)`);
